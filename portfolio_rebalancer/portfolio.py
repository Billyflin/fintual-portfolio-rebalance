"""Portfolio holdings, target allocations, and pure rebalancing logic."""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass
from decimal import Decimal
from enum import StrEnum

from .exceptions import InvalidAllocationError, InvalidHoldingError
from .stock import Numeric, Stock, to_decimal

_ZERO = Decimal("0")
_ONE = Decimal("1")
AllocationMapping = (
    Mapping[Stock, Numeric] | Mapping[str, Numeric] | Mapping[Stock | str, Numeric]
)


def _format_quantity(value: Decimal) -> str:
    """Format a Decimal share count without scientific notation (e.g., 10 instead of 1E+1)."""
    text = f"{value:f}"
    if "." in text:
        text = text.rstrip("0").rstrip(".")
    return text or "0"


class TradeAction(StrEnum):
    """Order side emitted by portfolio rebalancing."""

    SELL = "SELL"
    BUY = "BUY"


@dataclass(frozen=True)
class RebalanceOrder:
    """Single buy or sell instruction produced by ``Portfolio.rebalance()``."""

    symbol: str
    action: TradeAction
    shares: Decimal
    amount: Decimal
    price: Decimal
    current_weight: Decimal
    target_weight: Decimal


@dataclass(frozen=True)
class PositionSnapshot:
    """Current vs. target valuation breakdown for one symbol in the portfolio."""

    symbol: str
    shares: Decimal
    price: Decimal
    current_value: Decimal
    target_value: Decimal
    current_weight: Decimal
    target_weight: Decimal
    drift_weight: Decimal


@dataclass(frozen=True)
class RebalancePlan:
    """Immutable result of ``Portfolio.rebalance()``."""

    total_value: Decimal
    orders: tuple[RebalanceOrder, ...]
    positions: tuple[PositionSnapshot, ...]

    @property
    def sells(self) -> tuple[RebalanceOrder, ...]:
        """Sell orders in execution order."""
        return tuple(order for order in self.orders if order.action is TradeAction.SELL)

    @property
    def buys(self) -> tuple[RebalanceOrder, ...]:
        """Buy orders in execution order."""
        return tuple(order for order in self.orders if order.action is TradeAction.BUY)

    @property
    def is_balanced(self) -> bool:
        """True when no trades are required."""
        return len(self.orders) == 0

    @property
    def total_sell_amount(self) -> Decimal:
        """Aggregate cash proceeds generated by sell orders."""
        return sum((order.amount for order in self.sells), _ZERO)

    @property
    def total_buy_amount(self) -> Decimal:
        """Aggregate cash required by buy orders."""
        return sum((order.amount for order in self.buys), _ZERO)

    def format_summary(self) -> str:
        """Render a human-readable summary of current vs. target positions and trades."""
        lines = [f"Portfolio total value: ${self.total_value:.2f}"]
        if self.positions:
            lines.append("Positions:")
            for pos in self.positions:
                cur_pct = pos.current_weight * Decimal("100")
                tgt_pct = pos.target_weight * Decimal("100")
                lines.append(
                    f"  - {pos.symbol}: {_format_quantity(pos.shares)} sh @ ${pos.price:.2f} "
                    f"= ${pos.current_value:.2f} ({cur_pct:.2f}% -> target {tgt_pct:.2f}%)"
                )

        if self.is_balanced:
            lines.append("Orders: portfolio is already balanced.")
        else:
            lines.append("Orders (SELL before BUY):")
            for order in self.orders:
                lines.append(
                    f"  - {order.action.value} {_format_quantity(order.shares)} {order.symbol} "
                    f"@ ${order.price:.2f} (${order.amount:.2f})"
                )
        return "\n".join(lines)


class Portfolio:
    """Manages stock holdings, target allocations, and self-funded rebalancing.

    Financial math uses ``decimal.Decimal`` throughout to avoid binary floating-point
    precision errors. Rebalancing is intentionally pure: ``rebalance()`` inspects the
    latest prices via ``Stock.current_price()`` and returns a ``RebalancePlan`` without
    mutating holdings in place, allowing callers to inspect, confirm, or persist orders
    independently.
    """

    def __init__(
        self,
        holdings: Mapping[Stock, Numeric] | None = None,
        allocations: AllocationMapping | None = None,
    ) -> None:
        self._stocks: dict[str, Stock] = {}
        self._holdings: dict[str, Decimal] = {}
        self._allocations: dict[str, Decimal] = {}

        if holdings is not None:
            for stock, shares in holdings.items():
                self.set_holding(stock, shares)

        if allocations is not None:
            self.set_allocations(allocations)

    @property
    def stocks(self) -> dict[str, Stock]:
        """Registered ``Stock`` objects keyed by uppercase symbol."""
        return dict(self._stocks)

    @property
    def holdings(self) -> dict[str, Decimal]:
        """Current share counts keyed by uppercase symbol."""
        return dict(self._holdings)

    @property
    def allocations(self) -> dict[str, Decimal]:
        """Target allocation weights (summing to 1) keyed by uppercase symbol."""
        return dict(self._allocations)

    def _register_stock(self, stock: Stock, *, error_cls: type[ValueError]) -> str:
        """Bind a ``Stock`` instance to its symbol, guarding against conflicting instances."""
        symbol = stock.symbol
        existing = self._stocks.get(symbol)
        if existing is not None and existing is not stock:
            raise error_cls(
                f"Conflicting Stock instances registered for symbol {symbol!r}; "
                "reuse the same Stock object to prevent diverging prices."
            )
        self._stocks[symbol] = stock
        return symbol

    def set_holding(self, stock: Stock, shares: Numeric) -> None:
        """Register or update share count for a stock (``shares >= 0``)."""
        if not isinstance(stock, Stock):
            raise InvalidHoldingError(f"Expected Stock instance, got {type(stock).__name__}")
        parsed_shares = to_decimal(
            shares,
            field_name=f"shares for {stock.symbol}",
            error_cls=InvalidHoldingError,
        )
        if parsed_shares < _ZERO:
            raise InvalidHoldingError(
                f"Shares for {stock.symbol} cannot be negative, got {parsed_shares}"
            )
        symbol = self._register_stock(stock, error_cls=InvalidHoldingError)
        self._holdings[symbol] = parsed_shares

    def set_allocations(self, allocations: AllocationMapping) -> None:
        """Replace target portfolio weights after validating range ``[0, 1]`` and sum ``1``."""
        if not allocations:
            raise InvalidAllocationError("Target allocations cannot be empty")

        pending_weights: dict[str, Decimal] = {}
        # Register against a temporary view first so failed updates leave state intact.
        pending_stocks: dict[str, Stock] = {}

        for key, weight in allocations.items():
            if isinstance(key, Stock):
                symbol = key.symbol
                existing = pending_stocks.get(symbol) or self._stocks.get(symbol)
                if existing is not None and existing is not key:
                    raise InvalidAllocationError(
                        f"Conflicting Stock instances for symbol {symbol!r}; "
                        "reuse the same Stock instance used in holdings."
                    )
                pending_stocks[symbol] = key
            elif isinstance(key, str):
                symbol = key.strip().upper()
                if not symbol:
                    raise InvalidAllocationError("Allocation stock symbol cannot be empty")
                if symbol not in self._stocks and symbol not in pending_stocks:
                    raise InvalidAllocationError(
                        f"Unknown stock symbol {symbol!r} in allocations; pass a Stock instance "
                        "or register its holding first."
                    )
            else:
                raise InvalidAllocationError(
                    f"Allocation keys must be Stock or str, got {type(key).__name__}"
                )

            if symbol in pending_weights:
                raise InvalidAllocationError(f"Duplicate allocation entry for symbol {symbol!r}")

            parsed_weight = to_decimal(
                weight,
                field_name=f"allocation for {symbol}",
                error_cls=InvalidAllocationError,
            )
            if parsed_weight < _ZERO or parsed_weight > _ONE:
                raise InvalidAllocationError(
                    f"Allocation weight for {symbol} must be between 0 and 1, got {parsed_weight}"
                )
            pending_weights[symbol] = parsed_weight

        total_weight = sum(pending_weights.values(), _ZERO)
        if total_weight != _ONE:
            raise InvalidAllocationError(
                f"Target allocations must sum to 1 (100%), got {total_weight}"
            )

        self._stocks.update(pending_stocks)
        self._allocations = pending_weights

    def total_value(self) -> Decimal:
        """Compute current market value across all non-zero holdings using latest prices."""
        total = _ZERO
        for symbol, shares in self._holdings.items():
            if shares > _ZERO:
                total += shares * self._stocks[symbol].current_price()
        return total

    def rebalance(self, *, min_trade_amount: Numeric = _ZERO) -> RebalancePlan:
        """Compute sell and buy trades needed to align holdings with target allocations.

        Behavior and trade-offs:
        - **Pure**: returns a ``RebalancePlan`` without mutating ``holdings``.
        - **SELL before BUY**: sell orders (including full liquidations of stocks omitted
          from ``allocations``, which have an implicit 0% target) are placed before buy
          orders so proceeds fund subsequent purchases.
        - **Fractional shares**: follows modern retail brokerage execution where orders can
          buy or sell fractional shares (fees, taxes, and lot rounding are out of scope).
        """
        threshold = to_decimal(
            min_trade_amount,
            field_name="min_trade_amount",
            error_cls=InvalidAllocationError,
        )
        if threshold < _ZERO:
            raise InvalidAllocationError(
                f"min_trade_amount cannot be negative, got {threshold}"
            )

        if not self._allocations:
            raise InvalidAllocationError("Target allocations must be set before rebalancing")

        # Re-check allocation invariant defensively in case subclass/state drifted.
        if sum(self._allocations.values(), _ZERO) != _ONE:
            raise InvalidAllocationError("Target allocations must sum to 1 (100%)")

        active_symbols = sorted(
            {
                symbol
                for symbol in (*self._holdings.keys(), *self._allocations.keys())
                if self._holdings.get(symbol, _ZERO) > _ZERO
                or self._allocations.get(symbol, _ZERO) > _ZERO
            }
        )

        # Fetch all active prices up front so missing prices fail cleanly before planning.
        prices = {symbol: self._stocks[symbol].current_price() for symbol in active_symbols}
        current_values = {
            symbol: self._holdings.get(symbol, _ZERO) * prices[symbol]
            for symbol in active_symbols
        }
        portfolio_total = sum(current_values.values(), _ZERO)

        if portfolio_total == _ZERO:
            positions = tuple(
                PositionSnapshot(
                    symbol=symbol,
                    shares=_ZERO,
                    price=prices[symbol],
                    current_value=_ZERO,
                    target_value=_ZERO,
                    current_weight=_ZERO,
                    target_weight=self._allocations.get(symbol, _ZERO),
                    drift_weight=-self._allocations.get(symbol, _ZERO),
                )
                for symbol in active_symbols
            )
            return RebalancePlan(total_value=_ZERO, orders=(), positions=positions)

        snapshots: list[PositionSnapshot] = []
        sells: list[RebalanceOrder] = []
        buys: list[RebalanceOrder] = []

        for symbol in active_symbols:
            shares = self._holdings.get(symbol, _ZERO)
            price = prices[symbol]
            current_val = current_values[symbol]
            current_wt = current_val / portfolio_total
            target_wt = self._allocations.get(symbol, _ZERO)
            target_val = portfolio_total * target_wt
            delta_val = target_val - current_val

            snapshots.append(
                PositionSnapshot(
                    symbol=symbol,
                    shares=shares,
                    price=price,
                    current_value=current_val,
                    target_value=target_val,
                    current_weight=current_wt,
                    target_weight=target_wt,
                    drift_weight=current_wt - target_wt,
                )
            )

            trade_amount = abs(delta_val)
            if trade_amount <= threshold:
                continue

            action = TradeAction.BUY if delta_val > _ZERO else TradeAction.SELL
            # Full liquidation keeps exact held share count to avoid 28-digit division dust.
            if action is TradeAction.SELL and target_wt == _ZERO:
                trade_shares = shares
            else:
                trade_shares = trade_amount / price

            order = RebalanceOrder(
                symbol=symbol,
                action=action,
                shares=trade_shares,
                amount=trade_amount,
                price=price,
                current_weight=current_wt,
                target_weight=target_wt,
            )
            if action is TradeAction.SELL:
                sells.append(order)
            else:
                buys.append(order)

        return RebalancePlan(
            total_value=portfolio_total,
            orders=tuple([*sells, *buys]),
            positions=tuple(snapshots),
        )
